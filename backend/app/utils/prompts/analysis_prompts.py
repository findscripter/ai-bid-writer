"""标书解析相关提示词。"""

from typing import Dict, List


def build_analysis_messages(
    file_content: str, analysis_type: str
) -> List[Dict[str, str]]:
    """构建文档分析消息。"""
    system_prompt = """你是一名专业的招标文件分析助手。请严格基于用户提供的招标文件原文完成分析任务。

通用要求：
1. 保持提取信息的全面性和准确性，尽量使用原文内容，不要自行编造
2. 只输出最终分析结果，不要输出额外说明、过程、提示语或客套话
3. 如果文档内容不足以支持某项结论，应明确说明原文未提及，不要凭空补充
"""

    file_prompt = f"""以下是完整招标文件全文，请先完整阅读，并仅基于原文完成后续任务：

{file_content}"""

    if analysis_type == "overview":
        task_prompt = """任务：提取并总结项目概述信息。

请重点关注以下方面：
1. 项目名称和基本信息
2. 项目背景和目的
3. 项目规模和预算
4. 项目时间安排
5. 项目要实施的具体内容
6. 主要技术特点
7. 其他关键要求

工作要求：
1. 保持提取信息的全面性和准确性，尽量使用原文内容，不要自己编写
2. 只关注与项目实施有关的内容，不提取商务信息
3. 直接返回整理好的项目概述，除此之外不返回任何其他内容
"""
    else:
        task_prompt = """任务：提取“目录生成必需输入”，用于后续把技术标目录与正文严格映射到采购文件。

你必须同时输出两类信息：
A. 第三章评审办法/详细评审标准（评分项）
B. 第五章采购人要求（技术与交付要求）

请按以下固定结构输出，标题和顺序不得变更：

# 一、评审表要点清单
对每个评审项按如下格式逐条输出：
【评审项ID】：E1/E2/E3...
【评审项名称】：
【分值或权重】：
【评审标准】：
【原文位置】：
【目录建议】：建议映射到技术标哪个章节名称

# 二、采购人要求要点清单
对每个采购人要求按如下格式逐条输出：
【要求ID】：R1/R2/R3...
【要求名称】：
【关键约束/指标】：
【必含关键词】：（数字、型号、术语，如 5%、6%、3%、10%、90%、RTX3090、6138、强化学习、减温水）
【原文位置】：
【目录建议】：建议映射到技术标哪个章节名称

# 三、覆盖校验清单（用于目录审核）
输出一个清单，格式：
- [ ] E1 是否被目录独立覆盖
- [ ] E2 是否被目录独立覆盖
...
- [ ] R1 是否被目录独立覆盖
- [ ] R2 是否被目录独立覆盖
...

严格要求：
1) 必须覆盖第三章与第五章，不得只提评分项。
2) 技术标目录与内容必须能与“评审表”与“采购人要求”一一对应。
3) 不输出与技术标无关的商务价格条目。
4) 若原文缺失某字段，明确写“未提及”，不要编造。
5) 除上述结构化结果外，不输出任何额外说明。
"""

    return [
        {"role": "system", "content": system_prompt},
        {"role": "user", "content": file_prompt},
        {"role": "user", "content": task_prompt},
    ]
